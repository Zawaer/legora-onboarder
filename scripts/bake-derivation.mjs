/**
 * Bakes a derivation into the repo as a committed fixture.
 *
 *   npm run bake -- <derive-response.json> [companySlug] [roleTitle]
 *
 * Why this exists: `data/derivations.json` is written to the project directory,
 * which is read-only on Vercel. The cache silently never persists there, so the
 * deployed demo re-derives on every single visit — three minutes and a dollar
 * or two each time, including for every judge who clicks the button and every
 * stranger who follows a link we posted. Measured on the live deployment:
 * two consecutive identical requests, 189s and 191s, both `cached: false`.
 *
 * A fixture that ships inside the bundle is immune to all of it: no disk, no
 * instance affinity, no cost, no cold path.
 *
 * It cannot go stale silently. The entry carries the `corpusHash` it was baked
 * from, and `readDerivation` already refuses any entry whose hash does not match
 * the corpus in front of it — so editing `lib/seed/legora.ts` makes this fixture
 * be ignored rather than served wrongly. Re-run this script to refresh it.
 *
 * The hash and key come from the real modules via the `@/` resolver hook rather
 * than being reimplemented here, so they cannot drift from what the server does.
 */

import { promises as fs } from "node:fs";
import path from "node:path";

const [, , sourcePath, slugArg = "legora", roleArg = "Legal Engineer"] = process.argv;

if (!sourcePath) {
  console.error("usage: npm run bake -- <derive-response.json> [slug] [role]");
  process.exit(1);
}

const { corpusFingerprint, derivationKey } = await import("@/lib/agent/cache");
const { getCompany } = await import("@/lib/seed");

const company = getCompany(slugArg);
if (!company) {
  console.error(`No seeded company "${slugArg}".`);
  process.exit(1);
}

const raw = JSON.parse(await fs.readFile(sourcePath, "utf8"));

// Accept an /api/derive response, a hire record, or a bare {role, plan}.
const hire = raw.hire ?? raw;
const role = raw.role ?? hire.derivedRole;
const plan = raw.plan ?? hire.plan;

if (!role || !plan) {
  console.error("No derivedRole/plan found in that file.");
  process.exit(1);
}

const entry = {
  key: derivationKey(slugArg, roleArg),
  companySlug: slugArg,
  roleTitle: roleArg,
  corpusHash: corpusFingerprint(company),
  role,
  plan,
  grounding: raw.grounding ?? { kept: role.evidence?.length ?? 0, dropped: 0 },
  derivedAt: raw.derivedAt ?? new Date().toISOString(),
};

const out = path.join("lib", "seed", "derivations.ts");
const banner = `/**
 * Baked derivations. Generated by \`npm run bake\` — do not hand-edit.
 *
 * A .ts module rather than a .json file so it is a plain import in both the
 * Next bundle and plain Node, with no import-attribute differences between them.
 */
import type { CachedDerivation } from "@/lib/agent/cache";

export const BAKED_DERIVATIONS: CachedDerivation[] = `;
await fs.writeFile(out, `${banner}${JSON.stringify([entry], null, 2)};\n`, "utf8");

console.log(`Baked ${out}`);
console.log(`  key         ${entry.key}`);
console.log(`  corpusHash  ${entry.corpusHash}`);
console.log(`  corpus      ${company.artifacts.length} artifacts, ${company.people.length} people`);
console.log(`  citations   ${role.evidence?.length ?? 0}`);
console.log(`  plan        ${plan.days?.length ?? 0} days`);
